class LightDpsTest {
    @Test fun `v2 colour encoding`() {
        assertEquals("007803e803e8", LightDps.formatColour(LightSchema.V2, Hsv(120f, 1f, 1f)))
        val hsv = LightDps.parseColour(LightSchema.V2, "00b401f40064")!!
        assertEquals(180f, hsv.h)
        assertEquals(0.5f, hsv.s)
        assertEquals(0.1f, hsv.v)
    }

    @Test fun `v1 colour encoding includes rgb`() {
        // pure red, full sat/val: ff0000 + 0000 + ff + ff
        assertEquals("ff00000000ffff", LightDps.formatColour(LightSchema.V1, Hsv(0f, 1f, 1f)))
    }

    @Test fun `detects schema and parses state`() {
        val dps = mapOf<String, Any?>("20" to true, "21" to "white", "22" to 1000L, "23" to 0L, "24" to "000003e803e8")
        assertEquals(LightSchema.V2, LightDps.detect(dps))
        val s = LightDps.parse(LightSchema.V2, dps)
        assertTrue(s.on)
        assertEquals(LightMode.WHITE, s.mode)
        assertEquals(1f, s.brightness)
        assertEquals(0f, s.temperature)
        assertEquals(LightSchema.V1, LightDps.detect(mapOf("1" to false)))
    }

    @Test fun `white command uses device ranges`() {
        assertEquals(mapOf("20" to true, "21" to "white", "22" to 10, "23" to 1000), LightDps.white(LightSchema.V2, 0f, 1f))
        assertEquals(mapOf("1" to true, "2" to "white", "3" to 255, "4" to 0), LightDps.white(LightSchema.V1, 1f, 0f))
    }
}

class DeviceConfigTest {
    @Test fun `setup link round trips awkward keys`() {
        val cfg = DeviceConfig("Desk strip", "bf0123456789abcdefgh", "192.168.1.50", "a&b=c d'e|f<g>h#", TuyaVersion.V34)
        assertEquals(cfg, DeviceConfig.fromSetupLink(cfg.toSetupLink()))
        assertTrue(cfg.isComplete)
    }

    @Test fun `rejects other links`() {
        assertNull(DeviceConfig.fromSetupLink("https://example.com/?id=1"))
    }
}
