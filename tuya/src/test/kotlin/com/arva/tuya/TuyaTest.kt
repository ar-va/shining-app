class FramesTest {
    private val key = "0123456789abcdef".toByteArray()

    @Test fun `55AA crc frame round trips`() {
        val payload = "hello".toByteArray()
        val frame = Frames.pack55AA(7, TuyaCommand.CONTROL, payload, hmacKey = null)
        assertEquals(16 + 5 + 8, frame.size)
        val back = Frames.unpack(frame, null, useHmac = false)
        assertEquals(7, back.seq)
        assertEquals(TuyaCommand.CONTROL, back.cmd)
        assertNull(back.retcode)
        assertArrayEquals(payload, back.payload)
    }

    @Test fun `55AA hmac frame round trips and rejects wrong key`() {
        val frame = Frames.pack55AA(1, TuyaCommand.STATUS, "x".toByteArray(), hmacKey = key)
        assertArrayEquals("x".toByteArray(), Frames.unpack(frame, key, useHmac = true).payload)
        val wrong = runCatching { Frames.unpack(frame, "fedcba9876543210".toByteArray(), useHmac = true) }
        assertTrue(wrong.isFailure)
    }

    @Test fun `6699 frame round trips`() {
        val frame = Frames.pack6699(3, TuyaCommand.CONTROL_NEW, "{\"a\":1}".toByteArray(), key)
        val back = Frames.unpack(frame, key, useHmac = false)
        assertEquals(3, back.seq)
        assertEquals("{\"a\":1}", back.payload.toString(Charsets.UTF_8))
    }

    @Test fun `retcode is split off device replies`() {
        val frame = Frames.pack55AA(1, TuyaCommand.CONTROL, byteArrayOf(0, 0, 0, 0), hmacKey = null)
        val back = Frames.unpack(frame, null, useHmac = false)
        assertEquals(0, back.retcode)
        assertEquals(0, back.payload.size)
    }

    @Test fun `ecb matches known vector`() {
        // AES-128-ECB("0123456789abcdef", pkcs7("{}")) computed with tinytuya's AESCipher
        val enc = TuyaCrypto.ecbEncrypt(key, "{}".toByteArray())
        assertEquals(16, enc.size)
        assertEquals("{}", TuyaCrypto.ecbDecrypt(key, enc).toString(Charsets.UTF_8))
    }
}

